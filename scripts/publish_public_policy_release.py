"""Apply a prepared six-asset PolicyAsset release through browser APIs.

This helper has two explicit stages. The author submits immutable Draft assets;
a different authenticated human publishes assets and the CAS-protected snapshot.
PolicyAsset has no separate API preview/review action, so this tool prints the
live plan and requires typed confirmation before every mutation phase.
"""

from __future__ import annotations

import argparse
import getpass
import json
import re
from datetime import datetime, timezone
from pathlib import Path
import subprocess
import sys
import urllib.error
import urllib.parse

from bootstrap_public_examples import (
    APIError, BrowserAPI, confirm, ensure_private_directory, validate_machine_env_path,
    verify_login_identity, verify_private_file, write_new_private_file,
)


ROOT = Path(__file__).resolve().parents[1]
ASSET_TYPES = ("model", "prompt", "tool", "memory", "knowledge", "runtime")
SNAPSHOT_KEYS = {
    "model": "ModelProfileID",
    "prompt": "PromptVersionID",
    "tool": "ToolPolicyID",
    "memory": "MemoryPolicyID",
    "knowledge": "KnowledgePolicyID",
    "runtime": "RuntimePolicyID",
}
MAX_RUN_BUDGET_TOKENS = 32_000
MAX_RUN_BUDGET_MICROS = 3_200_000
MAX_DAILY_BUDGET_CENTS = 1000


def load_plan(path: Path) -> dict:
    value = json.loads(path.read_text(encoding="utf-8"))
    return validate_plan(value)


def validate_plan(value: dict) -> dict:
    plan = value.get("policy_publication") if isinstance(value, dict) else None
    if not isinstance(plan, dict) or plan.get("schema") != "policyasset-preparation/v1" or plan.get("preparation_only") is not True:
        raise ValueError("file must be the offline example-release-bundle output with policy_publication")
    scope = plan.get("scope")
    if not isinstance(scope, dict) or any(not isinstance(scope.get(key), str) or not scope[key] for key in (
        "tenant_id", "department_id", "application_id", "agent_id", "agent_version_id",
    )):
        raise ValueError("prepared policy scope is incomplete")
    assets = plan.get("assets")
    if not isinstance(assets, list) or len(assets) != 6:
        raise ValueError("prepared policy must contain exactly six assets")
    by_type = {}
    for item in assets:
        if not isinstance(item, dict) or item.get("type") not in ASSET_TYPES or item["type"] in by_type:
            raise ValueError("prepared policy contains a missing or duplicate asset family")
        body = item.get("create_request_template", {}).get("body")
        if not isinstance(body, dict) or body.get("id") != item.get("id") or body.get("type") != item.get("type"):
            raise ValueError("prepared create request does not match its asset identity")
        if body.get("scope") != scope or not isinstance(body.get("content"), dict):
            raise ValueError("prepared policy body does not match the exact publication scope")
        if not isinstance(item.get("content_hash"), str) or len(item["content_hash"]) != 64:
            raise ValueError("prepared policy content hash is missing")
        by_type[item["type"]] = item
    if set(by_type) != set(ASSET_TYPES):
        raise ValueError("prepared policy must contain model, prompt, tool, memory, knowledge and runtime")
    snapshot = plan.get("publish_snapshot_request_template", {}).get("body")
    if not isinstance(snapshot, dict) or snapshot.get("scope") != scope:
        raise ValueError("prepared snapshot request does not match the exact publication scope")
    preparer = value.get("public_policy_preparation", {}).get("author") if isinstance(value.get("public_policy_preparation"), dict) else None
    if not isinstance(preparer, str) or not preparer:
        raise ValueError("plan must be generated by this helper so its exact submitting human is recorded")
    return {"plan": plan, "scope": scope, "assets": by_type, "snapshot_template": snapshot, "author": preparer}


def validate_deployment_endpoint(value: str) -> str:
    if not isinstance(value, str) or not value or any(char.isspace() for char in value):
        raise ValueError("prepare stage requires a clean explicit HTTP(S) deployment endpoint")
    try:
        parsed = urllib.parse.urlsplit(value)
        # Accessing .port also validates malformed ports and bracket syntax.
        _port = parsed.port
    except ValueError:
        raise ValueError("deployment endpoint must be a valid HTTP(S) URL without credentials, query or fragment") from None
    if (parsed.scheme not in {"http", "https"} or not parsed.hostname
            or parsed.username is not None or parsed.password is not None
            or parsed.query or parsed.fragment):
        raise ValueError("deployment endpoint must be a valid HTTP(S) URL without credentials, query or fragment")
    return value


def verify_bundle_endpoint(value: dict, endpoint: str) -> None:
    requests = value.get("requests") if isinstance(value, dict) else None
    deployments = [item for item in requests if isinstance(item, dict)
                   and item.get("stage") == "deploy" and item.get("method") == "POST"] if isinstance(requests, list) else []
    if len(deployments) != 1 or not isinstance(deployments[0].get("body"), dict) or deployments[0]["body"].get("endpoint_ref") != endpoint:
        raise ValueError("prepared Catalog deployment endpoint differs from the explicitly requested endpoint")


def prepare_plan(args: argparse.Namespace) -> None:
    if not all((args.example, args.artifact_digest, args.publisher, args.version_id, args.installation_id, args.deployment_id, args.endpoint, args.policy_input, args.output)):
        raise ValueError("prepare stage requires --example, --artifact-digest, --publisher, --version-id, --installation-id, --deployment-id, --endpoint, --policy-input and --output")
    endpoint = validate_deployment_endpoint(args.endpoint)
    output = args.output.expanduser()
    validate_machine_env_path(output)
    if output.is_symlink():
        raise ValueError("plan output may not be a symlink")
    command = [
        "go", "run", "./cmd/example-release-bundle",
        "--example", str((ROOT / args.example).resolve()) if not Path(args.example).is_absolute() else str(Path(args.example)),
        "--artifact-digest", args.artifact_digest,
        "--publisher", args.publisher,
        "--tenant", args.tenant,
        "--department", args.department,
        "--application", args.application,
        "--version-id", args.version_id,
        "--installation-id", args.installation_id,
        "--deployment-id", args.deployment_id,
        "--endpoint", endpoint,
        "--policy-input", str((ROOT / args.policy_input).resolve()) if not Path(args.policy_input).is_absolute() else str(Path(args.policy_input)),
    ]
    try:
        completed = subprocess.run(command, cwd=ROOT / "platform", check=True, capture_output=True, text=True, encoding="utf-8")
    except (OSError, subprocess.CalledProcessError):
        raise RuntimeError("offline example-release-bundle preparation failed; inspect local inputs and CLI diagnostics") from None
    try:
        value = json.loads(completed.stdout)
    except ValueError:
        raise RuntimeError("offline example-release-bundle did not return valid JSON") from None
    verify_bundle_endpoint(value, endpoint)
    value["public_policy_preparation"] = {"author": args.publisher}
    validate_plan(value)
    ensure_private_directory(output.parent)
    if output.exists():
        verify_private_file(output)
        try:
            existing = json.loads(output.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            raise RuntimeError("output already exists and is not a readable plan; no file was overwritten") from None
        if existing != value:
            raise RuntimeError("output already contains a different release plan; choose a new private output path")
        print("Exact release plan already exists; no file was overwritten.")
        return
    write_new_private_file(output, json.dumps(value, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps({"result": "offline_policy_plan_saved", "path": str(output.resolve()), "author": args.publisher, "api_called": False}, ensure_ascii=False))


def scope_query(scope: dict) -> str:
    return urllib.parse.urlencode(scope)


def asset_path(asset_type: str, asset_id: str, scope: dict) -> str:
    return "/api/modules/policyasset/assets/{}/{}?{}".format(
        urllib.parse.quote(asset_type, safe=""), urllib.parse.quote(asset_id, safe=""), scope_query(scope),
    )


def read_live_asset(api: BrowserAPI, item: dict, scope: dict) -> dict | None:
    try:
        value = api.call("GET", asset_path(item["type"], item["id"], scope))
    except APIError as error:
        if error.status == 404 and error.code == "RESOURCE_NOT_FOUND":
            return None
        raise
    body = item["create_request_template"]["body"]
    if not isinstance(value, dict) or any(value.get(key) != expected for key, expected in {
        "id": item["id"], "type": item["type"], "scope": scope,
        "content_hash": item["content_hash"], "content": body["content"],
    }.items()):
        raise RuntimeError("live PolicyAsset differs from the prepared ID, scope, content or digest; stop and prepare a new immutable ID")
    if not isinstance(value.get("revision"), int) or value["revision"] < 1 or not isinstance(value.get("created_by"), str) or not value["created_by"]:
        raise RuntimeError("live PolicyAsset is missing its revision or human author identity")
    if value.get("status") not in {"draft", "published"}:
        raise RuntimeError("live PolicyAsset has an unknown status")
    return value


def create_drafts(api: BrowserAPI, release: dict, actor: str) -> None:
    if actor != release["author"]:
        raise RuntimeError("authenticated author must match the principal recorded by offline preparation")
    missing = []
    current = {}
    for typ in ASSET_TYPES:
        item = release["assets"][typ]
        live = read_live_asset(api, item, release["scope"])
        if live is None:
            missing.append(item)
        elif live["status"] != "draft":
            raise RuntimeError(f"{typ}/{item['id']} already exists as {live['status']}; use a new immutable release ID")
        elif live["created_by"] != actor:
            raise RuntimeError(f"{typ}/{item['id']} was drafted by another human; do not reuse another author's change")
        else:
            current[typ] = live
    if not missing:
        print("All six exact Draft assets already exist under this author; no API mutation was needed.")
        return
    summary = [{"type": item["type"], "id": item["id"], "content_hash": item["content_hash"]} for item in missing]
    print(json.dumps({"operation": "create_policy_drafts", "scope": release["scope"], "assets": summary}, ensure_ascii=False, indent=2))
    phrase = "create drafts {}@{}".format(release["scope"]["agent_id"], release["scope"]["agent_version_id"])
    if not confirm(phrase):
        raise RuntimeError("PolicyAsset Draft creation cancelled")
    for item in missing:
        body = item["create_request_template"]["body"]
        api.call("POST", "/api/modules/policyasset/assets", body)
        live = read_live_asset(api, item, release["scope"])
        if live is None or live["status"] != "draft" or live["created_by"] != actor:
            raise RuntimeError(f"created PolicyAsset {item['type']}/{item['id']} did not verify as this author's exact Draft")
        current[item["type"]] = live
    print(json.dumps({"result": "six_exact_drafts_verified", "author": actor, "asset_count": len(current)}, ensure_ascii=False))


def snapshot_value(snapshot: dict, key: str):
    # Handles Go initialisms such as ModelProfileID -> model_profile_id.
    snake = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", key).lower()
    return snapshot.get(key, snapshot.get(snake))


def current_snapshot(api: BrowserAPI, scope: dict) -> dict:
    try:
        value = api.call("GET", "/api/modules/policyasset/snapshots/current?" + scope_query(scope))
    except APIError as error:
        # The platform returns RESOURCE_NOT_FOUND when this exact scope has
        # never had a published snapshot. Treat that canonical empty state as
        # revision zero so the first publication can use the normal CAS API;
        # authorization and all other errors still fail closed.
        if error.status == 404 and error.code == "RESOURCE_NOT_FOUND":
            return {"Revision": 0, "Hash": ""}
        raise
    if not isinstance(value, dict):
        raise RuntimeError("current PolicyAsset snapshot response is invalid")
    revision = snapshot_value(value, "Revision")
    if not isinstance(revision, int) or revision < 0:
        raise RuntimeError("current PolicyAsset snapshot revision is invalid")
    return value


def snapshot_already_uses(snapshot: dict, release: dict) -> bool:
    if snapshot_value(snapshot, "Revision") == 0:
        return False
    for typ, key in SNAPSHOT_KEYS.items():
        if snapshot_value(snapshot, key) != release["assets"][typ]["id"]:
            return False
    expected_rule = release["snapshot_template"].get("rule", {})
    actual_rule = snapshot_value(snapshot, "Rule") or {}
    if not isinstance(actual_rule, dict):
        return False
    for field in ("version", "checksum"):
        title = field.title() if field == "version" else "Checksum"
        if actual_rule.get(field, actual_rule.get(title, "")) != expected_rule.get(field, ""):
            return False
    return True


def ensure_publishable_policy(release: dict) -> None:
    """Reject preparation placeholders and fail-closed budgets before any publish write."""
    model = release["assets"]["model"]["create_request_template"]["body"]["content"]
    runtime = release["assets"]["runtime"]["create_request_template"]["body"]["content"]
    target_fields = ("provider", "model", "model_version_id", "embedding_provider", "embedding_model", "embedding_model_version_id")
    if any(not isinstance(model.get(field), str) or not model[field].strip() or "REPLACE_" in model[field] for field in target_fields):
        raise RuntimeError("publication is blocked until the approved model_version_id is filled from model governance")
    prices = (model.get("input_micros_per_1k_tokens"), model.get("output_micros_per_1k_tokens"))
    if any(type(value) is not int or value <= 0 for value in prices):
        raise RuntimeError("publication is blocked until approved non-zero model prices are filled from model governance")
    if type(model.get("budget_cents")) is not int or not 0 < model["budget_cents"] <= MAX_DAILY_BUDGET_CENTS:
        raise RuntimeError("publication is blocked unless an explicit finite daily budget of at most 1000 cents is configured")
    run_budget = runtime.get("run_budget")
    if not isinstance(run_budget, dict) or type(run_budget.get("limit_tokens")) is not int or type(run_budget.get("limit_micros")) is not int or run_budget["limit_tokens"] <= 0 or run_budget["limit_micros"] <= 0:
        raise RuntimeError("publication is blocked until positive RunBudget limits are explicitly set")
    if run_budget["limit_tokens"] > MAX_RUN_BUDGET_TOKENS or run_budget["limit_micros"] > MAX_RUN_BUDGET_MICROS:
        raise RuntimeError("publication is blocked because RunBudget exceeds the reviewed 32000-token / 3200000-micro ceiling")
    maximum_priced_cost = (run_budget["limit_tokens"] * max(prices) + 999) // 1000
    if run_budget["limit_micros"] > maximum_priced_cost:
        raise RuntimeError("publication is blocked because the micro ceiling exceeds the configured model price at the token cap")
    knowledge = release["assets"]["knowledge"]["create_request_template"]["body"]["content"]
    if not knowledge.get("document_bindings"):
        raise RuntimeError("publication is blocked until actual source IDs, document versions and owners are bound in KnowledgePolicy")


def current_effective_price(api: BrowserAPI, model_version_id: str, now: datetime | None = None) -> dict:
    """Read the current approved Model Governance price through its public API."""
    query = urllib.parse.urlencode({"model_version_id": model_version_id, "limit": 200})
    response = api.call("GET", "/api/modules/model-governance/prices?" + query)
    if not isinstance(response, dict) or not isinstance(response.get("items"), list):
        raise RuntimeError("Model Governance price list response is invalid; policy publication is blocked")
    # The current API exposes neither a count nor a continuation token. Its
    # server clamps this list to 200 newest rows, so a full page cannot prove
    # that the effective interval is unique across the complete history.
    if len(response["items"]) >= 200:
        raise RuntimeError("Model Governance returned a full 200-row PriceVersion page without pagination metadata; uniqueness cannot be verified")
    now = now or datetime.now(timezone.utc)
    active = []
    for row in response["items"]:
        if not isinstance(row, dict) or row.get("model_version_id") != model_version_id or row.get("status") != "approved":
            continue
        try:
            starts = datetime.fromisoformat(row["effective_from"].replace("Z", "+00:00"))
            ends_raw = row.get("effective_until")
            ends = datetime.fromisoformat(ends_raw.replace("Z", "+00:00")) if ends_raw else None
        except (KeyError, AttributeError, TypeError, ValueError):
            raise RuntimeError("Model Governance returned an invalid PriceVersion interval; policy publication is blocked") from None
        if starts.tzinfo is None or (ends is not None and ends.tzinfo is None):
            raise RuntimeError("Model Governance returned a timezone-free PriceVersion interval; policy publication is blocked")
        if starts <= now < (ends or datetime.max.replace(tzinfo=timezone.utc)):
            active.append(row)
    if len(active) != 1:
        raise RuntimeError("exactly one currently effective approved PriceVersion must exist for the selected model_version_id")
    row = active[0]
    if not isinstance(row.get("id"), str) or not row["id"] or row.get("currency") != "USD":
        raise RuntimeError("current approved PriceVersion must have an ID and USD currency before publication")
    for key in ("input_micros_per_1k_tokens", "output_micros_per_1k_tokens"):
        if type(row.get(key)) is not int or row[key] <= 0:
            raise RuntimeError("current approved PriceVersion has invalid non-zero rates; policy publication is blocked")
    return row


def verify_policy_price(api: BrowserAPI, release: dict, now: datetime | None = None) -> dict:
    model = release["assets"]["model"]["create_request_template"]["body"]["content"]
    version_id = model["model_version_id"]
    price = current_effective_price(api, version_id, now)
    if any(model.get(field) != price.get(field) for field in (
        "input_micros_per_1k_tokens", "output_micros_per_1k_tokens",
    )):
        raise RuntimeError("PolicyAsset rates differ from the current approved Model Governance PriceVersion; update the Draft plan before publishing")
    return price


def submit_snapshot_cas(api: BrowserAPI, request: dict) -> dict:
    """Submit exactly once; a 409 or uncertain response requires live inspection."""
    return api.call("POST", "/api/modules/policyasset/snapshots/publish", request)


def publish_release(api: BrowserAPI, release: dict, actor: str) -> None:
    ensure_publishable_policy(release)
    price = verify_policy_price(api, release)
    print(json.dumps({"model_governance_price_version": price["id"], "model_version_id": price["model_version_id"], "currency": price["currency"], "input_micros_per_1k_tokens": price["input_micros_per_1k_tokens"], "output_micros_per_1k_tokens": price["output_micros_per_1k_tokens"]}, ensure_ascii=False))
    published = {}
    pending = []
    for typ in ASSET_TYPES:
        item = release["assets"][typ]
        live = read_live_asset(api, item, release["scope"])
        if live is None:
            raise RuntimeError(f"{typ}/{item['id']} is missing; author must submit all six Draft assets first")
        if live["created_by"] == actor:
            raise RuntimeError("publisher must be a different human from every PolicyAsset author")
        if live["status"] == "draft":
            pending.append((item, live))
        else:
            published[typ] = live

    current = current_snapshot(api, release["scope"])
    if not pending and snapshot_already_uses(current, release):
        print(json.dumps({"result": "exact_policy_snapshot_already_active", "revision": snapshot_value(current, "Revision"), "hash": snapshot_value(current, "Hash")}, ensure_ascii=False))
        return

    print(json.dumps({
        "operation": "publish_policy_assets_and_snapshot",
        "publisher": actor,
        "authors": {typ: read_live_asset(api, release["assets"][typ], release["scope"])["created_by"] for typ in ASSET_TYPES},
        "snapshot_expected_revision": snapshot_value(current, "Revision"),
        "assets_to_publish": [{"type": item["type"], "id": item["id"], "expected_revision": live["revision"], "content_hash": live["content_hash"]} for item, live in pending],
        "assets_already_published": [{"type": typ, "id": live["id"], "revision": live["revision"]} for typ, live in published.items()],
        "scope": release["scope"],
        "note": "PolicyAsset has no separate preview or Review API; current Identity policy.manage and API authorization remain authoritative.",
    }, ensure_ascii=False, indent=2))
    phrase = "publish six policies {}@{}".format(release["scope"]["agent_id"], release["scope"]["agent_version_id"])
    if not confirm(phrase):
        raise RuntimeError("PolicyAsset publication cancelled")

    for item, live in pending:
        base_path = "/api/modules/policyasset/assets/{}/{}".format(
            urllib.parse.quote(item["type"], safe=""), urllib.parse.quote(item["id"], safe=""),
        )
        api.call("POST", base_path + "/publish", {"scope": release["scope"], "expected_revision": live["revision"]})
        verified = read_live_asset(api, item, release["scope"])
        if verified is None or verified["status"] != "published" or verified["revision"] != live["revision"] + 1:
            raise RuntimeError(f"published {item['type']}/{item['id']} did not verify at the expected next revision")
        published[item["type"]] = verified
    if set(published) != set(ASSET_TYPES):
        raise RuntimeError("not all six immutable PolicyAsset revisions are published")

    latest = current_snapshot(api, release["scope"])
    if snapshot_already_uses(latest, release):
        print(json.dumps({"result": "exact_policy_snapshot_already_active", "revision": snapshot_value(latest, "Revision"), "hash": snapshot_value(latest, "Hash")}, ensure_ascii=False))
        return
    expected_snapshot_revision = snapshot_value(latest, "Revision")
    refs = {typ: {"id": published[typ]["id"], "revision": published[typ]["revision"]} for typ in ASSET_TYPES}
    request = {"scope": release["scope"], "expected_revision": expected_snapshot_revision, "assets": refs}
    if "rule" in release["snapshot_template"]:
        request["rule"] = release["snapshot_template"]["rule"]
    print(json.dumps({"operation": "publish_policy_snapshot_cas", "expected_revision": expected_snapshot_revision, "assets": refs, "scope": release["scope"]}, ensure_ascii=False, indent=2))
    if not confirm("publish snapshot {}@{} rev{}".format(release["scope"]["agent_id"], release["scope"]["agent_version_id"], expected_snapshot_revision)):
        raise RuntimeError("PolicyAsset snapshot CAS cancelled")
    # Deliberately one attempt. A CAS conflict or uncertain response must be
    # inspected against the live snapshot before an operator starts another run.
    result = submit_snapshot_cas(api, request)
    if not isinstance(result, dict) or snapshot_value(result, "Revision") != expected_snapshot_revision + 1:
        raise RuntimeError("snapshot API response did not verify at the expected next revision")
    print(json.dumps({"result": "six_asset_policy_snapshot_published", "revision": snapshot_value(result, "Revision"), "hash": snapshot_value(result, "Hash"), "publisher": actor}, ensure_ascii=False))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--plan", type=Path, help="offline JSON from this helper's prepare stage")
    parser.add_argument("--stage", choices=("prepare", "create-drafts", "publish"), required=True, help="offline preparation, author submission, or separate human publication")
    parser.add_argument("--username", help="current independently authenticated human principal")
    parser.add_argument("--base-url", default="http://127.0.0.1:8080", help="browser gateway origin; remote hosts require HTTPS")
    parser.add_argument("--example", help="example source directory for offline prepare stage")
    parser.add_argument("--artifact-digest", help="actual image sha256 digest")
    parser.add_argument("--publisher", help="exact author/submitting principal ID recorded in the plan")
    parser.add_argument("--tenant", default="tenant-demo")
    parser.add_argument("--department", default="dept-demo")
    parser.add_argument("--application", default="app-demo")
    parser.add_argument("--version-id")
    parser.add_argument("--installation-id")
    parser.add_argument("--deployment-id")
    parser.add_argument("--endpoint", help="exact HTTP(S) deployment endpoint reachable from the platform; required for prepare")
    parser.add_argument("--policy-input", type=Path, help="completed six-policy JSON input")
    parser.add_argument("--output", type=Path, help="new private output path under .local-secrets")
    args = parser.parse_args()
    try:
        if args.stage == "prepare":
            prepare_plan(args)
            return 0
        if args.plan is None or not args.username:
            parser.error("--plan and --username are required for API stages")
        release = load_plan(args.plan)
        api = BrowserAPI(args.base_url)
        password = getpass.getpass(f"Password for {args.username}: ")
        if not password:
            raise ValueError("password is required")
        api.login(args.username, password)
        scope = release["scope"]
        api.select_workspace({"tenant_id": scope["tenant_id"], "department_id": scope["department_id"], "application_id": scope["application_id"]})
        verify_login_identity(api.call("GET", "/auth/me"), args.username, {"tenant_id": scope["tenant_id"], "department_id": scope["department_id"], "application_id": scope["application_id"]})
        if args.stage == "create-drafts":
            create_drafts(api, release, args.username)
        else:
            publish_release(api, release, args.username)
        return 0
    except (OSError, ValueError, RuntimeError, APIError, urllib.error.URLError, KeyError, TypeError, AttributeError) as error:
        print("Public PolicyAsset publication stopped: " + str(error), file=sys.stderr)
        if isinstance(error, APIError) and error.status == 409:
            print("Live revision conflict: re-read and review the current asset/snapshot; this helper never retries a stale CAS.", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
