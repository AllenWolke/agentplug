func (m *Module) readPage(w http.ResponseWriter, query url.Values) (int, int, bool) {
	page, pageSize := 1, DefaultUsagePageSize
	if value := query.Get("page"); value != "" {
		parsed, err := strconv.Atoi(value)
		if err != nil || parsed < 1 || parsed > MaxUsagePage {
			m.error(w, http.StatusBadRequest, "INVALID_QUERY")
			return 0, 0, false
		}
		page = parsed
	}
	if value := query.Get("page_size"); value != "" {
		parsed, err := strconv.Atoi(value)
		if err != nil || parsed < 1 || parsed > MaxUsagePageSize {
			m.error(w, http.StatusBadRequest, "INVALID_QUERY")
			return 0, 0, false
		}
		pageSize = parsed
	}
	if err := validateUsagePage(page, pageSize); err != nil {
		m.error(w, http.StatusBadRequest, "INVALID_QUERY")
		return 0, 0, false
	}
	return page, pageSize, true
}

func (m *Module) readQuery(w http.ResponseWriter, r *http.Request, fixedRunID string, allowed ...string) (url.Values, Scope, time.Time, time.Time, bool) {
	if !m.authorized(r) {
		m.error(w, http.StatusUnauthorized, "UNAUTHENTICATED")
		return nil, Scope{}, time.Time{}, time.Time{}, false
	}
	query := r.URL.Query()
	allowedKeys := make(map[string]struct{}, len(allowed))
	for _, key := range allowed {
		allowedKeys[key] = struct{}{}
	}
	for key, values := range query {
		if _, ok := allowedKeys[key]; !ok || len(values) != 1 {
			m.error(w, http.StatusBadRequest, "INVALID_QUERY")
			return nil, Scope{}, time.Time{}, time.Time{}, false
		}
	}
	for key, maximum := range map[string]int{"page": MaxUsagePage, "page_size": MaxUsagePageSize} {
		if raw, exists := query[key]; exists {
			parsed, err := strconv.Atoi(strings.TrimSpace(raw[0]))
			if err != nil || parsed < 1 || parsed > maximum {
				m.error(w, http.StatusBadRequest, "INVALID_QUERY")
				return nil, Scope{}, time.Time{}, time.Time{}, false
			}
		}
	}
	value := func(key string, required bool) (string, bool) {
		values, exists := query[key]
		if !exists {
			return "", !required
		}
		if len(values) != 1 {
			return "", false
		}
		value := strings.TrimSpace(values[0])
		return value, value != ""
	}
	fromText, fromOK := value("from", true)
	toText, toOK := value("to", true)
	if !fromOK || !toOK {
		m.error(w, http.StatusBadRequest, "INVALID_QUERY")
		return nil, Scope{}, time.Time{}, time.Time{}, false
	}
	from, fromErr := time.Parse(time.RFC3339Nano, fromText)
	to, toErr := time.Parse(time.RFC3339Nano, toText)
	if fromErr != nil || toErr != nil || !from.Before(to) {
		m.error(w, http.StatusBadRequest, "INVALID_QUERY")
		return nil, Scope{}, time.Time{}, time.Time{}, false
	}
	scope := Scope{
		TenantID: strings.TrimSpace(r.Header.Get("X-Tenant-ID")), DepartmentID: strings.TrimSpace(r.Header.Get("X-Department-ID")), ApplicationID: strings.TrimSpace(r.Header.Get("X-Application-ID")),
	}
	scope.RunID = fixedRunID
	for _, key := range []string{"agent_id", "agent_version_id", "run_id"} {
		if raw, exists := query[key]; exists {
			filter := strings.TrimSpace(raw[0])
			if filter == "" {
				m.error(w, http.StatusBadRequest, "INVALID_QUERY")
				return nil, Scope{}, time.Time{}, time.Time{}, false
			}
			switch key {
			case "agent_id":
				scope.AgentID = filter
			case "agent_version_id":
				scope.AgentVersionID = filter
			case "run_id":
				scope.RunID = filter
			}
		}
	}
	if err := validateUsageRead(scope, from, to); err != nil {
		m.error(w, http.StatusBadRequest, "INVALID_SCOPE_OR_RANGE")
		return nil, Scope{}, time.Time{}, time.Time{}, false
	}
	if !m.authorizeBrowserRead(w, r, scope) {
		return nil, Scope{}, time.Time{}, time.Time{}, false
	}
	return query, scope, from.UTC(), to.UTC(), true
}

func (m *Module) authorizeBrowserRead(w http.ResponseWriter, r *http.Request, scope Scope) bool {
	return m.authorizeBrowserAction(w, r, ActionReadUsage, scope)
}

func (m *Module) authorizeBrowserAction(w http.ResponseWriter, r *http.Request, action UsageAction, scope Scope) bool {
	if r.Header.Get("X-Browser-Module") != "1" {
		return true
	}
	actor := Actor{
		TenantID: strings.TrimSpace(r.Header.Get("X-Tenant-ID")), DepartmentID: strings.TrimSpace(r.Header.Get("X-Department-ID")), ApplicationID: strings.TrimSpace(r.Header.Get("X-Application-ID")),
		PrincipalType: strings.TrimSpace(r.Header.Get("X-Principal-Type")), PrincipalID: strings.TrimSpace(r.Header.Get("X-Principal-ID")),
	}
	if actor.PrincipalType != "user" || actor.PrincipalID == "" || actor.TenantID == "" || actor.DepartmentID == "" || actor.ApplicationID == "" || m.authorizer == nil {
		m.error(w, http.StatusForbidden, "FORBIDDEN")
		return false
	}
	if actor.TenantID != scope.TenantID || actor.DepartmentID != scope.DepartmentID || actor.ApplicationID != scope.ApplicationID {
		m.error(w, http.StatusForbidden, "FORBIDDEN")
		return false
	}
	if err := m.authorizer.AuthorizeUsageCost(r.Context(), actor, action, scope); err != nil {
		if errors.Is(err, ErrUsageForbidden) {
			m.error(w, http.StatusForbidden, "FORBIDDEN")
		} else {
			m.error(w, http.StatusServiceUnavailable, "IDENTITY_UNAVAILABLE")
		}
		return false
	}
	return true
}

func (m *Module) usageQueryError(w http.ResponseWriter, err error) {
	if errors.Is(err, ErrInvalidUsageQuery) {
		m.error(w, http.StatusBadRequest, "INVALID_QUERY")
		return
	}
	m.error(w, http.StatusInternalServerError, "USAGE_QUERY_FAILED")
}

func (m *Module) authorized(r *http.Request) bool {
	if m.internalToken == "" {
		return true
	}
	value := strings.TrimSpace(strings.TrimPrefix(r.Header.Get("Authorization"), "Bearer "))
	if value == "" {
		value = strings.TrimSpace(r.Header.Get("X-Internal-Token"))
	}
	return len(value) == len(m.internalToken) && subtle.ConstantTimeCompare([]byte(value), []byte(m.internalToken)) == 1
}

func decode(r *http.Request, target any) error {
	decoder := json.NewDecoder(io.LimitReader(r.Body, 1<<20))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(target); err != nil {
		return err
	}
	var extra any
	if err := decoder.Decode(&extra); err == nil {
		return errors.New("multiple json values")
	}
	return nil
}

func (m *Module) storeError(w http.ResponseWriter, err error) {
	status, code := http.StatusInternalServerError, "INTERNAL_ERROR"
	switch {
	case errors.Is(err, ErrInvalidUsage):
		status, code = http.StatusBadRequest, "INVALID_USAGE"
	case errors.Is(err, ErrUsageConflict):
		status, code = http.StatusConflict, "IDEMPOTENCY_CONFLICT"
	case errors.Is(err, ErrBudgetExceeded):
		status, code = http.StatusPaymentRequired, "USAGE_BUDGET_EXCEEDED"
	}
	m.error(w, status, code)
}

func (m *Module) error(w http.ResponseWriter, status int, code string) {
	m.json(w, status, map[string]any{"error": map[string]string{"code": code}})
}

func (m *Module) json(w http.ResponseWriter, status int, value any) {
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(status)
	_ = json.NewEncoder(w).Encode(value)
}

