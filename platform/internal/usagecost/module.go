package usagecost

// HTTP boundary for the platform-owned usage and cost ledger. The endpoint is
// intentionally internal; Agents publish usage through the capability gateway
// and product workers can use the same Port without owning SQL tables.

import (
	"context"
	"crypto/subtle"
	"encoding/json"
	"errors"
	"io"
	"net/http"
	"net/url"
	"strconv"
	"strings"
	"time"

	"github.com/lexagent/platform/internal/bootstrap"
)

const ActionManageLedgerBudget UsageAction = "manage_ledger_budget"

type Module struct {
	store         Store
	internalToken string
	authorizer    Authorizer
}

type Store interface {
	EnsureSchema(context.Context) error
	SetBudget(context.Context, Budget) error
	Apply(context.Context, Event) (Snapshot, error)
	GetSnapshot(context.Context, Scope) (Snapshot, error)
}

func NewModule(store Store, internalToken string) *Module {
	return &Module{store: store, internalToken: strings.TrimSpace(internalToken)}
}

func (m *Module) Name() string { return "usage-cost" }

func (m *Module) Start(ctx context.Context) error {
	if m.store == nil {
		return errors.New("usage store is required")
	}
	// Schema is installed by the versioned migration command, never Start.
	// Schema由独立版本迁移命令安装，Start不得改库。
	return ctx.Err()
}

func (m *Module) Ready() error {
	if m.store == nil {
		return errors.New("usage store is required")
	}
	return nil
}

func (m *Module) Close(context.Context) error { return nil }

func (m *Module) Handler() http.Handler {
	mux := http.NewServeMux()
	mux.HandleFunc("/budgets", m.budgets)
	mux.HandleFunc("/events", m.events)
	mux.HandleFunc("/snapshots", m.snapshots)
	mux.HandleFunc("/usage/aggregate", m.usageAggregate)
	mux.HandleFunc("/usage/events", m.usageEvents)
	mux.HandleFunc("/usage/runs", m.usageRuns)
	mux.HandleFunc("/usage/runs/", m.usageRunSteps)
	return mux
}

// SetAuthorizer injects Identity's current browser read and budget policy.
// Browser operations fail closed if it has not been configured.
func (m *Module) SetAuthorizer(authorizer Authorizer) {
	if m != nil {
		m.authorizer = authorizer
	}
}

func (m *Module) budgets(w http.ResponseWriter, r *http.Request) {
	if !m.authorized(r) {
		m.error(w, http.StatusUnauthorized, "UNAUTHENTICATED")
		return
	}
	if r.Header.Get("X-Browser-Module") != "" {
		if r.Header.Get("X-Browser-Module") != "1" {
			m.error(w, http.StatusForbidden, "FORBIDDEN")
			return
		}
	}
	if r.Method != http.MethodPost {
		m.error(w, http.StatusMethodNotAllowed, "METHOD_NOT_ALLOWED")
		return
	}
	var budget Budget
	if err := decode(r, &budget); err != nil {
		m.error(w, http.StatusBadRequest, "INVALID_REQUEST")
		return
	}
	if r.Header.Get("X-Browser-Module") == "1" {
		// Accept only the canonical five-part legacy key. Exact coordinates,
		// not a string prefix, define the administrator's management boundary.
		parts := strings.Split(budget.ScopeKey, ":")
		if len(parts) != 5 {
			m.error(w, http.StatusBadRequest, "INVALID_BUDGET_SCOPE")
			return
		}
		for _, part := range parts {
			if part == "" || strings.TrimSpace(part) != part || len(part) > 128 || strings.ContainsAny(part, "*\x00\r\n") {
				m.error(w, http.StatusBadRequest, "INVALID_BUDGET_SCOPE")
				return
			}
		}
		scope := Scope{TenantID: parts[0], DepartmentID: parts[1], ApplicationID: parts[2], AgentID: parts[3], AgentVersionID: parts[4]}
		if !m.authorizeBrowserAction(w, r, ActionManageLedgerBudget, scope) {
			return
		}
	}
	if err := m.store.SetBudget(r.Context(), budget); err != nil {
		m.storeError(w, err)
		return
	}
	m.json(w, http.StatusCreated, budget)
}

func (m *Module) events(w http.ResponseWriter, r *http.Request) {
	if !m.authorized(r) {
		m.error(w, http.StatusUnauthorized, "UNAUTHENTICATED")
		return
	}
	// Usage is generated by trusted execution/capability recorders; a human
	// gateway credential must never let a browser invent cost or token facts.
	if r.Header.Get("X-Browser-Module") != "" {
		m.error(w, http.StatusForbidden, "TRUSTED_USAGE_WRITER_REQUIRED")
		return
	}
	if r.Method != http.MethodPost {
		m.error(w, http.StatusMethodNotAllowed, "METHOD_NOT_ALLOWED")
		return
	}
	var event Event
	if err := decode(r, &event); err != nil {
		m.error(w, http.StatusBadRequest, "INVALID_REQUEST")
		return
	}
	snapshot, err := m.store.Apply(r.Context(), event)
	if err != nil {
		m.storeError(w, err)
		return
	}
	m.json(w, http.StatusAccepted, map[string]any{"event": event, "snapshot": snapshot})
}

func (m *Module) snapshots(w http.ResponseWriter, r *http.Request) {
	if !m.authorized(r) {
		m.error(w, http.StatusUnauthorized, "UNAUTHENTICATED")
		return
	}
	if r.Method != http.MethodGet {
		m.error(w, http.StatusMethodNotAllowed, "METHOD_NOT_ALLOWED")
		return
	}
	scope := Scope{TenantID: r.Header.Get("X-Tenant-ID"), DepartmentID: r.Header.Get("X-Department-ID"), ApplicationID: r.Header.Get("X-Application-ID"), AgentID: r.Header.Get("X-Agent-ID"), AgentVersionID: r.Header.Get("X-Agent-Version-ID"), RunID: r.Header.Get("X-Run-ID")}
	if !m.authorizeBrowserRead(w, r, scope) {
		return
	}
	snapshot, err := m.store.GetSnapshot(r.Context(), scope)
	if err != nil {
		m.storeError(w, err)
		return
	}
	m.json(w, http.StatusOK, snapshot)
}

func (m *Module) usageAggregate(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodGet {
		m.error(w, http.StatusMethodNotAllowed, "METHOD_NOT_ALLOWED")
		return
	}
	_, scope, from, to, ok := m.readQuery(w, r, "", "from", "to", "agent_id", "agent_version_id", "run_id")
	if !ok {
		return
	}
	reader, ok := m.store.(UsageReader)
	if !ok {
		m.error(w, http.StatusNotImplemented, "USAGE_QUERY_UNAVAILABLE")
		return
	}
	result, err := reader.AggregateUsage(r.Context(), scope, from, to)
	if err != nil {
		m.usageQueryError(w, err)
		return
	}
	m.json(w, http.StatusOK, result)
}

