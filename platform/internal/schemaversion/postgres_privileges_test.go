package schemaversion

import (
	"context"
	"crypto/rand"
	"database/sql"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"strings"
	"testing"
	"time"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/stdlib"
)

func TestPostgresRuntimePrivilegesEffectiveGrants(t *testing.T) {
	db := postgresSchemaFixture(t)
	ctx := context.Background()
	var database string
	if err := db.QueryRow(`SELECT current_database()`).Scan(&database); err != nil {
		t.Fatal(err)
	}
	role := fmt.Sprintf("runtime_fixture_%d", time.Now().UnixNano())
	secret := make([]byte, 32)
	if _, err := rand.Read(secret); err != nil {
		t.Fatal(err)
	}
	password := hex.EncodeToString(secret)
	exec := func(query string) {
		t.Helper()
		if _, err := db.ExecContext(ctx, query); err != nil {
			t.Fatal(err)
		}
	}
	exec(`CREATE ROLE "` + role + `" LOGIN PASSWORD '` + password + `'`)
	t.Cleanup(func() {
		_, _ = db.Exec(`DROP OWNED BY "` + role + `"`)
		if _, err := db.Exec(`DROP ROLE "` + role + `"`); err != nil {
			t.Error(err)
		}
	})
	exec(`REVOKE CREATE ON SCHEMA public FROM PUBLIC`)
	exec(`REVOKE TEMP ON DATABASE "` + database + `" FROM PUBLIC`)
	if err := ApplyPostgres(ctx, db, func(ctx context.Context, borrowedDB *sql.DB) error {
		_, err := borrowedDB.Exec(`CREATE TABLE platform_runtime_fixture(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, value TEXT NOT NULL)`)
		return err
	}); err != nil {
		t.Fatal(err)
	}
	exec(`GRANT SELECT ON platform_schema_version TO "` + role + `"`)
	exec(`GRANT SELECT,INSERT,UPDATE,DELETE ON platform_runtime_fixture TO "` + role + `"`)
	exec(`GRANT USAGE ON SEQUENCE platform_runtime_fixture_id_seq TO "` + role + `"`)
	config, err := pgx.ParseConfig(os.Getenv("PUBLIC_TEST_POSTGRES_MIGRATION_DSN"))
	if err != nil {
		t.Fatal("fixture DSN invalid")
	}
	config.Database = database
	config.User = role
	config.Password = password
	runtime := stdlib.OpenDB(*config)
	t.Cleanup(func() { _ = runtime.Close() })
	if err := runtime.PingContext(ctx); err != nil {
		t.Fatalf("runtime authentication: %T", err)
	}
	assertSafe := func() {
		t.Helper()
		if err := CheckRuntimePrivileges(ctx, runtime); err != nil {
			t.Fatal(err)
		}
	}
	assertSafe()
	if err := CheckRuntimePrivileges(ctx, db); !errors.Is(err, ErrRuntimePrivileges) {
		t.Fatal("migration owner accepted for runtime")
	}
	var id int64
	if err := runtime.QueryRow(`INSERT INTO platform_runtime_fixture(value) VALUES('safe') RETURNING id`).Scan(&id); err != nil || id != 1 {
		t.Fatalf("identity insert: %d %v", id, err)
	}
	for _, statement := range []string{`CREATE TABLE forbidden_runtime_ddl(id INT)`, `CREATE TEMP TABLE forbidden_runtime_temp(id INT)`, `UPDATE platform_schema_version SET checksum='forbidden'`, `SELECT setval('platform_runtime_fixture_id_seq',100)`} {
		if _, err := runtime.Exec(statement); err == nil {
			t.Fatalf("runtime executed forbidden SQL: %s", statement)
		}
	}
	for _, test := range []struct{ name, grant, revoke string }{
		{"schema CREATE", `GRANT CREATE ON SCHEMA public TO ROLE`, `REVOKE CREATE ON SCHEMA public FROM ROLE`},
		{"database CREATE", `GRANT CREATE ON DATABASE DB TO ROLE`, `REVOKE CREATE ON DATABASE DB FROM ROLE`},
		{"temporary DDL", `GRANT TEMP ON DATABASE DB TO ROLE`, `REVOKE TEMP ON DATABASE DB FROM ROLE`},
		{"truncate", `GRANT TRUNCATE ON platform_runtime_fixture TO ROLE`, `REVOKE TRUNCATE ON platform_runtime_fixture FROM ROLE`},
		{"grant option", `GRANT SELECT ON platform_runtime_fixture TO ROLE WITH GRANT OPTION`, `REVOKE GRANT OPTION FOR SELECT ON platform_runtime_fixture FROM ROLE`},
		{"version mutation", `GRANT UPDATE ON platform_schema_version TO ROLE`, `REVOKE UPDATE ON platform_schema_version FROM ROLE`},
		{"sequence reset", `GRANT UPDATE ON SEQUENCE platform_runtime_fixture_id_seq TO ROLE`, `REVOKE UPDATE ON SEQUENCE platform_runtime_fixture_id_seq FROM ROLE`},
		{"role membership", `GRANT pg_read_all_data TO ROLE`, `REVOKE pg_read_all_data FROM ROLE`},
		{"bypass RLS", `ALTER ROLE ROLE BYPASSRLS`, `ALTER ROLE ROLE NOBYPASSRLS`},
		{"create database", `ALTER ROLE ROLE CREATEDB`, `ALTER ROLE ROLE NOCREATEDB`},
		{"create role", `ALTER ROLE ROLE CREATEROLE`, `ALTER ROLE ROLE NOCREATEROLE`},
		{"replication", `ALTER ROLE ROLE REPLICATION`, `ALTER ROLE ROLE NOREPLICATION`},
		{"PUBLIC grant", `GRANT CREATE ON SCHEMA public TO PUBLIC`, `REVOKE CREATE ON SCHEMA public FROM PUBLIC`},
	} {
		t.Run(test.name, func(t *testing.T) {
			replace := func(q string) string {
				tokens := strings.Fields(q)
				for i, token := range tokens {
					if token == "ROLE" && !(i == 1 && tokens[0] == "ALTER") {
						tokens[i] = `"` + role + `"`
					}
					if token == "DB" {
						tokens[i] = `"` + database + `"`
					}
				}
				return strings.Join(tokens, " ")
			}
			exec(replace(test.grant))
			if err := CheckRuntimePrivileges(ctx, runtime); !errors.Is(err, ErrRuntimePrivileges) {
				t.Fatalf("unsafe effective grant accepted: %v", err)
			}
			exec(replace(test.revoke))
			assertSafe()
		})
	}
	exec(`CREATE SCHEMA runtime_owned AUTHORIZATION "` + role + `"`)
	if err := CheckRuntimePrivileges(ctx, runtime); !errors.Is(err, ErrRuntimePrivileges) {
		t.Fatal("schema owner accepted")
	}
	exec(`DROP SCHEMA runtime_owned`)
	assertSafe()
	var owner string
	if err := db.QueryRow(`SELECT current_user`).Scan(&owner); err != nil {
		t.Fatal(err)
	}
	exec(`ALTER TABLE platform_runtime_fixture OWNER TO "` + role + `"`)
	if err := CheckRuntimePrivileges(ctx, runtime); !errors.Is(err, ErrRuntimePrivileges) {
		t.Fatal("table owner accepted")
	}
	exec(`ALTER TABLE platform_runtime_fixture OWNER TO "` + owner + `"`)
	exec(`GRANT SELECT,INSERT,UPDATE,DELETE ON platform_runtime_fixture TO "` + role + `"`)
	exec(`GRANT USAGE ON SEQUENCE platform_runtime_fixture_id_seq TO "` + role + `"`)
	assertSafe()

	exec(`CREATE SCHEMA foreign_scope`)
	exec(`CREATE TABLE foreign_scope.private_data(id INT)`)
	exec(`GRANT SELECT ON foreign_scope.private_data TO "` + role + `"`)
	if err := CheckRuntimePrivileges(ctx, runtime); !errors.Is(err, ErrRuntimePrivileges) {
		t.Fatal("foreign-schema DML accepted")
	}
	exec(`REVOKE SELECT ON foreign_scope.private_data FROM "` + role + `"`)
	assertSafe()
	exec(`CREATE FUNCTION public.runtime_security_definer_fixture() RETURNS INT LANGUAGE SQL SECURITY DEFINER AS 'SELECT 1'`)
	if err := CheckRuntimePrivileges(ctx, runtime); !errors.Is(err, ErrRuntimePrivileges) {
		t.Fatal("PUBLIC security-definer execution accepted")
	}
	exec(`REVOKE EXECUTE ON FUNCTION public.runtime_security_definer_fixture() FROM PUBLIC`)
	assertSafe()
}
